// Captures real screenshots of the iclear UI (mock data mode) for the promo.
// Needs the frontend served on :1420 (`cd frontend && trunk serve --port 1420`,
// or `cargo tauri dev`). Writes promo/shots.js (JPEG data URIs) so the canvas
// can draw them without tainting (file:// images would).
//
//   node promo/shots.mjs
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { openPage } from './cdp.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const PAGES = ['Panel', 'Memoria', 'Ventiladores'];

// The promo uses a smaller fictional demo machine (16 GB) than the app's
// mock data, so a few texts are swapped before each capture.
const DEMO_TEXT = [
  ['MacBook Pro', 'MacBook Air'],
  ['MacBook-Pro.local', 'Mac.local'],
  ['Apple M3 Pro', 'Apple M3'],
  ['re:\\d+,\\d GB de 24,0 GB', '13,9 GB de 16,0 GB'],
  ['24 GB en total', '16 GB en total'],
  ['Mac de 24 GB', 'Mac de 16 GB'],
  ['5,4 GB / 8 GB', '3,2 GB / 4 GB'],
  ['24,0 GB', '16,0 GB'],
  ['21,3 GB', '13,1 GB'],
  ['34 GB', '23 GB'],
  ['19,7 GB', '12,4 GB'],
  ['11,3 GB', '7,6 GB'],
  ['9,1 GB', '5,8 GB'],
  ['5,4 GB', '3,2 GB'],
];
const sanitize = `(() => {
  const map = ${JSON.stringify(DEMO_TEXT)};
  const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = w.nextNode())) {
    let v = n.nodeValue;
    for (const [a, b] of map) v = a.startsWith('re:') ? v.replace(new RegExp(a.slice(3), 'g'), b) : v.split(a).join(b);
    if (v.trim() === '12' && n.parentElement && /Núcleos/.test(n.parentElement.parentElement?.textContent || '')) v = v.replace('12', '8');
    if (v !== n.nodeValue) n.nodeValue = v;
  }
})()`;

const page = await openPage('http://localhost:1420/', { width: 1440, height: 900, match: 'localhost:1420' });
await page.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1.5, mobile: false });
// Wait for the WASM app to mount its navigation.
for (let i = 0; i < 60 && !(await page.evaluate(`!!document.querySelector('button[aria-label="Panel"]')`)); i++) await page.sleep(250);
await page.sleep(1500);

const shots = {};
for (const name of PAGES) {
  const clicked = await page.evaluate(`(() => {
    const b = [...document.querySelectorAll('button, a')].find(e => e.getAttribute('aria-label') === ${JSON.stringify(name)} || e.textContent.trim().startsWith(${JSON.stringify(name)}));
    if (b) b.click();
    return !!b;
  })()`);
  if (!clicked) throw new Error(`No encontré la página ${name} en el nav`);
  // Apps runs a (mock) scan; give every page time to settle its animations.
  await page.sleep(name === 'Apps' ? 4500 : 2200);
  // Hide the "mock data" badge: the promo shows the product, not the dev mode.
  await page.evaluate(`[...document.querySelectorAll('span,div,p')].filter(e => e.childElementCount <= 2 && e.textContent.length < 60 && /datos simulados/i.test(e.textContent)).forEach(e => e.style.visibility = 'hidden')`);
  await page.evaluate(sanitize);
  const shot = await page.send('Page.captureScreenshot', { format: 'jpeg', quality: 88 });
  shots[name] = 'data:image/jpeg;base64,' + shot.result.data;
  console.log(`✓ ${name} (${Math.round(shot.result.data.length * 0.75 / 1024)} KB)`);
}
await page.close();

writeFileSync(join(here, 'shots.js'), `// Generated by shots.mjs — real UI screenshots (mock data).\nwindow.SHOTS = ${JSON.stringify(shots)};\n`);
console.log(join(here, 'shots.js'));
